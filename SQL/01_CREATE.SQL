CREATE DATABASE RENTAL_CARS;

CREATE TABLE CATEGORIAS (
    ID_CATEGORIA INT PRIMARY KEY AUTO_INCREMENT,
    NOMBRE_CATEGORIA VARCHAR(50) NOT NULL,
    DESCRIPCION VARCHAR(120)
);

CREATE TABLE SUCURSALES (
    ID_SUCURSAL INT PRIMARY KEY AUTO_INCREMENT,
    NOMBRE_SUCURSAL VARCHAR(80) NOT NULL,
    DIRECCION_SUCURSAL VARCHAR(120) NOT NULL,
    CIUDAD VARCHAR(50) NOT NULL,
    TELEFONO VARCHAR(30)
);

CREATE TABLE CLIENTES (
    ID_CLIENTE INT PRIMARY KEY AUTO_INCREMENT,
    NOMBRE_CLIENTE VARCHAR(50) NOT NULL,
    EMAIL_CLIENTE VARCHAR(50) DEFAULT NULL,
    TELEFONO_CLIENTE VARCHAR(50),
    CIUDAD_CLIENTE VARCHAR(50) NOT NULL,
    FECHA_REGISTRO_CLIENTE DATE,
    LICENCIA_CONDUCIR_CLIENTE VARCHAR(30) NOT NULL
);

CREATE TABLE EMPLEADOS (
    ID_EMPLEADO INT PRIMARY KEY AUTO_INCREMENT,
    NOMBRE_EMPLEADO VARCHAR(80) NOT NULL,
    CARGO_EMPLEADO VARCHAR(50) NOT NULL,
    ID_SUCURSAL INT NOT NULL,
    FECHA_INGRESO_EMPLEADO DATE NOT NULL,
    SALARIO_EMPLEADO DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (ID_SUCURSAL) REFERENCES SUCURSALES(ID_SUCURSAL)
);

CREATE TABLE VEHICULOS (
    ID_VEHICULO INT PRIMARY KEY AUTO_INCREMENT,
    MARCA_VEHICULO VARCHAR(100) NOT NULL,
    MODELO_VEHICULO VARCHAR(100) NOT NULL,
    ANIO_AUTO INT NOT NULL,
    PRECIO_DIA DECIMAL(9,2) NOT NULL,
    ESTADO_VEHICULO TINYINT(1) DEFAULT 1,
    ID_CATEGORIA INT NOT NULL,
    ID_SUCURSAL INT NOT NULL,
    PATENTE_VEHICULO VARCHAR(15) NOT NULL,
    KM_ACTUAL INT NOT NULL,
    FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIAS(ID_CATEGORIA),
    FOREIGN KEY (ID_SUCURSAL) REFERENCES SUCURSALES(ID_SUCURSAL)
);

CREATE TABLE ALQUILERES (
    ID_ALQUILER INT PRIMARY KEY AUTO_INCREMENT,
    ID_CLIENTE INT NOT NULL,
    ID_VEHICULO INT NOT NULL,
    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE,
    TOTAL DECIMAL(9,2),
    ID_EMPLEADO INT,
    ID_SUCURSAL_RETIRO INT NOT NULL,
    ID_SUCURSAL_DEVOLUCION INT,
    ESTADO_ALQUILER VARCHAR(20) NOT NULL,
    FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTES(ID_CLIENTE),
    FOREIGN KEY (ID_VEHICULO) REFERENCES VEHICULOS(ID_VEHICULO),
    FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS(ID_EMPLEADO),
    FOREIGN KEY (ID_SUCURSAL_RETIRO) REFERENCES SUCURSALES(ID_SUCURSAL),
    FOREIGN KEY (ID_SUCURSAL_DEVOLUCION) REFERENCES SUCURSALES(ID_SUCURSAL)
);

CREATE TABLE RESERVAS (
    ID_RESERVA INT PRIMARY KEY AUTO_INCREMENT,
    ID_CLIENTE INT NOT NULL,
    ID_VEHICULO INT NOT NULL,
    FECHA_RESERVA DATE NOT NULL,
    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE NOT NULL,
    ESTADO_RESERVA VARCHAR(20) NOT NULL,
    FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTES(ID_CLIENTE),
    FOREIGN KEY (ID_VEHICULO) REFERENCES VEHICULOS(ID_VEHICULO)
);

CREATE TABLE MANTENIMIENTO (
    ID_MANTENIMIENTO INT PRIMARY KEY AUTO_INCREMENT,
    ID_VEHICULO INT NOT NULL,
    FECHA_MANTENIMIENTO DATE NOT NULL,
    TIPO_MANTENIMIENTO VARCHAR(50) NOT NULL,
    COSTO_MANTENIMIENTO DECIMAL(9,2) NOT NULL,
    OBSERVACIONES_MANTENIMIENTO VARCHAR(200),
    FOREIGN KEY (ID_VEHICULO) REFERENCES VEHICULOS(ID_VEHICULO)
);

CREATE TABLE PAGOS (
    ID_PAGO INT PRIMARY KEY AUTO_INCREMENT,
    ID_ALQUILER INT NOT NULL,
    FECHA_PAGO DATE NOT NULL,
    MONTO_PAGO DECIMAL(9,2) NOT NULL,
    FOREIGN KEY (ID_ALQUILER) REFERENCES ALQUILERES(ID_ALQUILER)
);

CREATE TABLE SEGUROS (
    ID_SEGURO INT PRIMARY KEY AUTO_INCREMENT,
    ID_ALQUILER INT NOT NULL,
    COMPANIA_SEGURO VARCHAR(80) NOT NULL,
    NUMERO_POLIZA VARCHAR(50) NOT NULL,
    COBERTURA_SEGURO VARCHAR(100) NOT NULL,
    COSTO_SEGURO DECIMAL(9,2) NOT NULL,
    FOREIGN KEY (ID_ALQUILER) REFERENCES ALQUILERES(ID_ALQUILER)
);

CREATE TABLE CHECK_ALQUILERES (
    ID_CHECK INT PRIMARY KEY AUTO_INCREMENT,
    ID_ALQUILER INT NOT NULL,
    TIPO_CHECK VARCHAR(10) NOT NULL,
    FECHA_CHECK DATETIME NOT NULL,
    KM_CHECK INT NOT NULL,
    NIVEL_COMBUSTIBLE INT NOT NULL,
    FOREIGN KEY (ID_ALQUILER) REFERENCES ALQUILERES(ID_ALQUILER)
);

CREATE TABLE MULTAS (
    ID_MULTA INT PRIMARY KEY AUTO_INCREMENT,
    ID_ALQUILER INT NOT NULL,
    FECHA_MULTA DATE NOT NULL,
    MOTIVO_MULTA VARCHAR(120) NOT NULL,
    MONTO_MULTA DECIMAL(9,2) NOT NULL,
    PAGADA TINYINT(1) NOT NULL DEFAULT 0,
    FOREIGN KEY (ID_ALQUILER) REFERENCES ALQUILERES(ID_ALQUILER)
);




        
    
    